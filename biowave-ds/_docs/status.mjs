#!/usr/bin/env node
// npm run status — writes STATUS.md: a per-platform checklist of every component and pattern.
// Generated, never edited. Sources: each <name>.md header (Plan · Code · Figma build · Review),
// contract state (contract.mjs) and the build order in ROADMAP.md. docs:check fails when STATUS.md is stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, SECTIONS, PLATFORM_LABEL, load, listComponents, plainStatus, componentPath } from './component-file.mjs';
import { contractState } from './contract.mjs';

const PLATS = ['web', 'tablet', 'mobile'];
const STACK = { web: 'React + MUI', tablet: 'Flutter + Material 3', mobile: 'Flutter + Material 3' };
const DONE = ['Built', 'In review', 'Approved'];
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const cleanName = (cell) => cell.replace(/\*\*/g, '').split(' — ')[0].split(' (')[0].trim();

// ROADMAP.md tables: | Day | Date | Component/Pattern | W | T | M | … |
export function roadmapItems() {
  const text = fs.readFileSync(path.join(ROOT, 'ROADMAP.md'), 'utf8');
  const items = { component: [], pattern: [] };
  let kind = null, day = null;
  for (const line of text.split('\n')) {
    if (/^## /.test(line)) { kind = /Phase [12]/.test(line) ? 'component' : /Phase 3/.test(line) ? 'pattern' : null; day = null; continue; }
    if (!kind || !line.startsWith('|')) continue;
    const c = line.split('|').slice(1, -1).map((x) => x.trim());
    if (c.length < 6 || /^-+$|^:?-+:?$/.test(c[0]) || c[0] === 'Day' || /^:?-/.test(c[3])) continue;
    if (c[0]) day = c[0].replace(/\*\*/g, '');
    if (/buffer/i.test(c[2])) continue;
    const name = cleanName(c[2]);
    const on = { web: c[3] === '●', tablet: c[4] === '●', mobile: c[5] === '●' };
    items[kind].push({ name, slug: slug(name), day, on });
  }
  return items;
}

const box = (ok) => (ok ? '- [x]' : '- [ ]');

function nextStep(plat, name, h, ct) {
  if (h.plan !== 'Finished') return `**Planner** — finish the plan (Plan is \`${h.plan || '—'}\`)`;
  if (ct.code !== 'current' || ct.figma !== 'current') return `**Planner** — regenerate contracts: \`npm run contract -- ${plat} ${name}\``;
  const reviewSaysFix = /changes requested/i.test(h.review);
  const track = (status, who, contract) => {
    if (status === 'Planned') return `**${who}** — build from \`${contract}\``;
    if (status === 'In progress') return `**${who}** — finish the build (In progress)`;
    if (status === 'Changes requested' || (status === 'Built' && reviewSaysFix)) return `**Fixer** — fix the open findings in Part E`;
    if (status === 'Built' || status === 'In review') return `**Reviewer** — review against the plan`;
    return null;
  };
  const steps = [
    track(h.code, 'Code Executor', `${name}-contract.md`),
    track(h.figma, 'Figma Agent', `figma-${name}-contract.md`),
  ].filter(Boolean);
  if (!steps.length) return '**Done** — publish Code Connect if not yet published';
  return [...new Set(steps)].join(' · then ');
}

export function expectedStatus() {
  const road = roadmapItems();
  const order = new Map(road.component.map((r, i) => [r.slug, r]));
  const out = [];
  out.push('# Status — Biowave components and patterns', '');
  out.push('> **Generated by `npm run status` — never edit by hand.** Sources: the header of each `<section>/components/<name>/<name>.md` (Plan · Code · Figma build · Review), the contract state, and the build order in [`ROADMAP.md`](ROADMAP.md). To change a status, edit the component file header and its section README row, then run `npm run status`. `npm run docs:check` fails when this file is out of date.');
  out.push('', '**Agents:** find your platform below. Each component lists the six checks in workflow order and the **Next** step with the role that owns it (AGENTS.md roles). Pick work only from rows whose Next names your role.', '');
  out.push('## Checklist steps', '');
  out.push('| # | Step | Ticked when |', '|---|---|---|');
  out.push('| 1 | Plan finished | header `Plan` = Finished |');
  out.push('| 2 | Contracts current | code and Figma contracts exist and match the plan |');
  out.push('| 3 | Code built | `Code` = Built · In review · Approved |');
  out.push('| 4 | Code approved | `Code` = Approved |');
  out.push('| 5 | Figma built | `Figma build` = Built · In review · Approved |');
  out.push('| 6 | Figma approved | `Figma build` = Approved → Code Connect is published |');
  out.push('');

  const data = {};
  for (const plat of PLATS) {
    const existing = listComponents(plat);
    const inScope = road.component.filter((r) => r.on[plat]).map((r) => r.slug);
    const names = [...new Set([...inScope, ...existing])];
    data[plat] = names.map((name) => {
      const r = order.get(name);
      const c = existing.includes(name) ? load(plat, name) : null;
      if (!c) return { name, label: r?.name ?? name, day: r?.day, started: false };
      const h = { plan: plainStatus(c.doc.header.Plan), code: plainStatus(c.doc.header.Code), figma: plainStatus(c.doc.header['Figma build']), review: plainStatus(c.doc.header.Review || '—') };
      const ct = contractState(plat, name);
      const label = r?.name ?? c.doc.header.Component?.split(' · ')[0] ?? name;
      return { name, label, day: r?.day, started: true, h, ct, c };
    });
  }

  out.push('## Summary', '');
  out.push('| Platform | In scope | Not started | Plan finished | Code built | Code approved | Figma built | Figma approved |', '|---|--:|--:|--:|--:|--:|--:|--:|');
  for (const plat of PLATS) {
    const rows = data[plat], s = rows.filter((x) => x.started);
    const n = (f) => s.filter(f).length;
    out.push(`| [${PLATFORM_LABEL[plat]}](#${plat}) | ${rows.length} | ${rows.length - s.length} | ${n((x) => x.h.plan === 'Finished')} | ${n((x) => DONE.includes(x.h.code))} | ${n((x) => x.h.code === 'Approved')} | ${n((x) => DONE.includes(x.h.figma))} | ${n((x) => x.h.figma === 'Approved')} |`);
  }
  out.push('');

  for (const plat of PLATS) {
    const rows = data[plat];
    out.push(`<a id="${plat}"></a>`, `## ${PLATFORM_LABEL[plat]} — ${STACK[plat]}`, '');
    out.push(`Section: [\`${SECTIONS[plat]}/README.md\`](${SECTIONS[plat]}/README.md)`, '');
    out.push('### Started', '');
    const started = rows.filter((x) => x.started).sort((a, b) => (+(a.day ?? 99) - +(b.day ?? 99)) || a.label.localeCompare(b.label));
    if (!started.length) out.push('_None yet._', '');
    for (const x of started) {
      const { h, ct } = x;
      out.push(`#### ${x.label}${x.day ? ` · Day ${x.day}` : ''}`, '');
      out.push(`File: [\`${componentPath(plat, x.name)}\`](${componentPath(plat, x.name)}) · Review: ${h.review}`, '');
      out.push(`${box(h.plan === 'Finished')} Plan finished — \`${h.plan}\``);
      out.push(`${box(ct.code === 'current' && ct.figma === 'current')} Contracts current — code \`${ct.code}\` · Figma \`${ct.figma}\``);
      out.push(`${box(DONE.includes(h.code))} Code built — \`${h.code}\``);
      out.push(`${box(h.code === 'Approved')} Code approved`);
      out.push(`${box(DONE.includes(h.figma))} Figma built — \`${h.figma}\``);
      out.push(`${box(h.figma === 'Approved')} Figma approved`);
      out.push('', `**Next:** ${nextStep(plat, x.name, h, ct)}`, '');
    }
    const todo = rows.filter((x) => !x.started);
    out.push('### Not started (roadmap order)', '');
    if (!todo.length) out.push('_All started._');
    for (const x of todo) out.push(`- [ ] ${x.label} · Day ${x.day} — **Planner**: write \`${componentPath(plat, x.name)}\``);
    out.push('');
  }

  out.push('## Patterns', '');
  out.push('Patterns start after the Complex release (Day 19 creates `7-patterns/`). ● = platform in scope.', '');
  out.push('| Done | Pattern | Day | Web | Tablet | Mobile |', '|:-:|---|--:|:-:|:-:|:-:|');
  const dot = (b) => (b ? '●' : '—');
  for (const p of road.pattern) {
    const done = fs.existsSync(path.join(ROOT, '7-patterns', `${p.slug}.md`));
    out.push(`| ${done ? '☑' : '☐'} | ${p.name} | ${p.day} | ${dot(p.on.web)} | ${dot(p.on.tablet)} | ${dot(p.on.mobile)} |`);
  }
  out.push('');
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(ROOT, 'STATUS.md');
  fs.writeFileSync(file, expectedStatus());
  console.log('✓ STATUS.md written');
}

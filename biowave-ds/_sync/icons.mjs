// Material Symbols icon index (D-18): _sync/figma-icons.json — Figma keys of the glyphs the Biowave specs use,
// read from the "Google · Material Symbols" library file (figma-files.json › icons) by figma-read-icons.js.
// On demand: only icons named in component specs are indexed (the library has ~4 150 sets).
//   npm run sync:icons:plan          → lists missing icons, writes _sync/figma-read-icons.generated.js
//   (run that script with use_figma in the icons file, save the output)
//   npm run sync:icons -- <dump…>    → merges the output into figma-icons.json
import fs from 'node:fs';
import path from 'node:path';
import { SYNC, ROOT, FIGMA_FILES, readJson, writeJson } from './lib.mjs';

export const ICONS_FILE = path.join(SYNC, 'figma-icons.json');
const TEMPLATE = path.join(SYNC, 'figma-read-icons.js');
const GENERATED = path.join(SYNC, 'figma-read-icons.generated.js');
const SECTIONS = ['3-web-components', '4-tablet-components', '5-mobile-components'];
const NAME = /^[a-z0-9][a-z0-9_]*$/;
const NOT_ICONS = new Set(['true', 'false', 'none', 'null']);
// Material Symbols names known to the installed font package (optional filter; Figma decides when absent)
function knownNames() {
  const f = path.join(ROOT, 'node_modules/@material-symbols/font-400/index.d.ts');
  return fs.existsSync(f) ? new Set([...fs.readFileSync(f, 'utf8').matchAll(/"([a-z0-9_]+)"/g)].map((m) => m[1])) : null;
}

/** Icon names a spec text refers to: Symbols.x_rounded, <Icon …>x</Icon>, MaterialSymbol name="x",
 *  backticked names on INSTANCE_SWAP rows and on "**Icons used:**" lines. */
export function iconNamesIn(text, known = knownNames()) {
  const s = new Set();
  for (const m of text.matchAll(/Symbols\.([a-z0-9_]+?)_rounded\b/g)) s.add(m[1]);
  for (const m of text.matchAll(/material-symbols-rounded"[^>]*>([a-z0-9_]+)<\/Icon>/g)) s.add(m[1]);
  for (const m of text.matchAll(/MaterialSymbol name="([a-z0-9_]+)"/g)) s.add(m[1]);
  const pick = (t) => { for (const m of t.matchAll(/`([^`]+)`/g)) if (NAME.test(m[1]) && !NOT_ICONS.has(m[1])) s.add(m[1]); };
  for (const line of text.split('\n')) {
    if (/\*\*Icons used:\*\*/.test(line)) pick(line);
    // D4 property rows: | Figma property | Type | Values | Default | Code prop | Code value | → Values + Default only
    else if (/^\|.*INSTANCE_SWAP/.test(line)) { const cells = line.split('|'); pick(`${cells[3] || ''} ${cells[4] || ''}`); }
  }
  return new Set([...s].filter((n) => !known || known.has(n)));
}

function specFiles() {
  const out = [];
  for (const sec of SECTIONS) {
    const dir = path.join(ROOT, sec, 'components');
    if (!fs.existsSync(dir)) continue;
    for (const name of fs.readdirSync(dir)) {
      const f = path.join(dir, name, `${name}.md`);
      if (fs.existsSync(f)) out.push(f);
    }
  }
  return out;
}

export function readIcons() { return readJson(ICONS_FILE) || { icons: {}, missing: {} }; }

/** name → [spec files] for every icon the specs use */
export function usedIcons() {
  const known = knownNames(), used = new Map();
  for (const f of specFiles()) for (const n of iconNamesIn(fs.readFileSync(f, 'utf8'), known))
    (used.get(n) || used.set(n, []).get(n)).push(path.relative(ROOT, f));
  return used;
}

export function iconsState() {
  const idx = readIcons(), used = usedIcons();
  const missing = [...used.keys()].filter((n) => !idx.icons[n] && !idx.missing?.[n]).sort();
  const notInLibrary = [...used.keys()].filter((n) => idx.missing?.[n]).sort();
  return { used, missing, notInLibrary, indexed: Object.keys(idx.icons).length, readAt: idx.readAt };
}

export function planIcons() {
  const st = iconsState();
  if (!st.missing.length) { console.log(`✓ icon index complete: ${st.used.size} icon(s) used by specs, all indexed`); return true; }
  const tpl = fs.readFileSync(TEMPLATE, 'utf8').replace('/*__NAMES__*/[]', JSON.stringify(st.missing));
  fs.writeFileSync(GENERATED, tpl);
  console.log(`⏳ ${st.missing.length} icon(s) not indexed: ${st.missing.join(', ')}`);
  console.log(`→ run ${path.relative(ROOT, GENERATED)} with use_figma on ${FIGMA_FILES.icons?.name} (${FIGMA_FILES.icons?.key}), save the output, then: npm run sync:icons -- <dump>`);
  return true;
}

export function saveIcons(dumps) {
  if (!dumps.length) { console.error('usage: sync.mjs icons <dump> [<dump> …]   (output of figma-read-icons.generated.js)'); return false; }
  const idx = readIcons(); idx.icons ||= {}; idx.missing ||= {};
  let added = 0, notFound = 0;
  for (const f of dumps) for (const line of fs.readFileSync(f, 'utf8').split('\n')) {
    const p = line.trim().split('|');
    if (p[0] === 'I') { idx.icons[p[1]] = { set: p[2], rounded: p[3], roundedFilled: p[4] }; delete idx.missing[p[1]]; added++; }
    if (p[0] === 'X') { idx.missing[p[1]] = p[2] || 'not in the icon library'; notFound++; }
  }
  const out = { $description: 'Generated by `npm run sync:icons` from _sync/figma-read-icons.generated.js output (D-18). Do not edit.',
    library: FIGMA_FILES.icons?.name, file: FIGMA_FILES.icons?.key, readAt: new Date().toISOString(),
    icons: Object.fromEntries(Object.entries(idx.icons).sort()), missing: Object.fromEntries(Object.entries(idx.missing).sort()) };
  writeJson(ICONS_FILE, out);
  console.log(`✓ ${path.relative(ROOT, ICONS_FILE)}: ${Object.keys(out.icons).length} icon(s) indexed (+${added}), ${notFound} not in the library`);
  return true;
}

// Figma library index (R-01): _sync/figma-library.json — every published Foundations variable, style and
// Doc Kit / icon component WITH ITS KEY, read from Figma by figma-read-library.js (never typed by hand).
// The Figma contracts look names up here, so the Figma Agent imports by key instead of searching by name.
import fs from 'node:fs';
import path from 'node:path';
import { SYNC, ROOT, FIGMA_FILES, sourceHash, hashFile, readJson, writeJson } from './lib.mjs';

export const LIBRARY_FILE = path.join(SYNC, 'figma-library.json');
const DOC_KIT = '2-foundations/figma-doc-kit.md';

export function readLibrary() { return readJson(LIBRARY_FILE); }

// fresh = read after the last token-source and Doc Kit change
export function libraryState() {
  const lib = readLibrary();
  if (!lib) return { ok: false, lib: null, reason: 'missing — run figma-read-library.js in Figma, then npm run sync:library' };
  const reasons = [];
  if (lib.sourceHash !== sourceHash()) reasons.push('token source changed since the last read');
  if (fs.existsSync(path.join(ROOT, DOC_KIT)) && lib.docKitHash !== hashFile(DOC_KIT)) reasons.push('Doc Kit spec changed since the last read');
  if (!lib.reach?.variables) reasons.push('library reachability from a component file not recorded');
  return { ok: !reasons.length, lib, reason: reasons.join('; ') };
}

export function saveLibrary(dumpFiles) {
  if (!dumpFiles.length) { console.error('usage: sync.mjs library <dump> [<dump> …]   (outputs of _sync/figma-read-library.js)'); process.exit(2); }
  const lib = { $description: 'Generated by `npm run sync:library` from _sync/figma-read-library.js output. Do not edit.', readAt: new Date().toISOString(),
    library: 'Biowave DS — Foundations', libraryKey: (readJson(path.join(SYNC, 'figma-files.json')).$project || {}).libraryKey || '',
    foundationsFile: FIGMA_FILES.foundations.key, sourceHash: sourceHash(), docKitHash: fs.existsSync(path.join(ROOT, DOC_KIT)) ? hashFile(DOC_KIT) : null,
    reach: null, variables: [], textStyles: [], effectStyles: [], paintStyles: [], gridStyles: [], components: [] };
  const prev = readLibrary() || {};
  const parts = new Set();
  for (const f of dumpFiles) {
    for (const line of fs.readFileSync(f, 'utf8').split('\n')) {
      const p = line.trim().split('|');
      switch (p[0]) {
        case 'F': parts.add(p[2]); break;
        case 'V': lib.variables.push({ collection: p[1], name: p[2], key: p[3], type: p[4], scopes: p[5] ? p[5].split(',') : [], web: p[6] || null, hidden: p[7] === '1' }); break;
        case 'T': lib.textStyles.push({ name: p[1], key: p[2] }); break;
        case 'E': lib.effectStyles.push({ name: p[1], key: p[2] }); break;
        case 'P': lib.paintStyles.push({ name: p[1], key: p[2] }); break;
        case 'G': lib.gridStyles.push({ name: p[1], key: p[2] }); break;
        case 'C': lib.components.push({ page: p[1], name: p[2], key: p[3], kind: p[4] }); break;
        case 'R': lib.reach = { library: p[1], collections: +p[2], variables: +p[3] }; break;
      }
    }
  }
  // parts not supplied this time are kept from the previous index
  if (!parts.has('variables')) lib.variables = prev.variables || [];
  if (!parts.has('styles')) for (const k of ['textStyles', 'effectStyles', 'paintStyles', 'gridStyles']) lib[k] = prev[k] || [];
  if (!parts.has('components')) lib.components = prev.components || [];
  if (!parts.has('reach')) lib.reach = prev.reach || null;
  const problems = [];
  if (!lib.variables.length) problems.push('no variables');
  if (lib.reach && lib.reach.variables < lib.variables.filter((v) => !v.hidden).length) problems.push(`only ${lib.reach.variables} library variables reachable from the component file, ${lib.variables.filter((v) => !v.hidden).length} published — republish the library`);
  writeJson(LIBRARY_FILE, lib);
  console.log(`✓ ${path.relative(ROOT, LIBRARY_FILE)}: ${lib.variables.length} variables · ${lib.textStyles.length} text / ${lib.effectStyles.length} effect / ${lib.paintStyles.length} paint styles · ${lib.components.length} components · reachable: ${lib.reach ? lib.reach.variables + ' variables' : 'not checked'}`);
  problems.forEach((p) => console.log('  ✗ ' + p));
  return !problems.length;
}

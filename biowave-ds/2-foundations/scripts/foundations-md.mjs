// Writes 2-foundations/tokens/Biowave Foundations.md — a plain-Markdown reference of every foundation token,
// generated from the token source on every `npm run tokens`. Never edit the output by hand.
import fs from 'node:fs';
import path from 'node:path';
import { loadAll, TOKENS, colorHex, contrast } from './lib/tokens.mjs';

const all = loadAll();
const L = all.theme.light, D = all.theme.dark;
const out = [];
const w = (s = '') => out.push(s);
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ').trim();
const kebab = (p) => p.replace(/\./g, '-');
const prim = (t) => (t.ref ? ' · ' + t.ref.replace('primitive.color.', '') : '');
const hex = (t) => colorHex(t.value);

// The surface (or fill) a foreground token is measured on.
function measuredOn(p) {
  let m;
  if ((m = p.match(/^color\.(text|icon)\.on\.(\w+)$/))) return `color.background.${m[2]}.default`;
  if ((m = p.match(/^color\.data\.tag\.(\d+)\.text$/))) return `color.data.tag.${m[1]}.background`;
  if (/^color\.(text|icon)\.inverse$/.test(p)) return 'color.surface.inverse';
  if (/^color\.(text|icon|link)\./.test(p) || /^color\.data\.(categorical|sequential)\./.test(p) || /^color\.border\.(bold|focus|brand|secondary|accent|success|error|warning|info)$/.test(p)) return 'color.surface.default';
  return null;
}

w('# Biowave Foundations');
w();
w('> GENERATED by `npm run tokens` (`2-foundations/scripts/foundations-md.mjs`) — do not edit. Source of truth: `2-foundations/tokens/**/*.json`.');
w('> Components use semantic tokens only. Each colour shows its Light and Dark value, the primitive it aliases (raw hex when none), and — for foreground tokens — the measured WCAG 2 contrast against the surface or fill it is meant for.');
w();
w('## Semantic colours');
const groups = [...new Set([...L.keys()].filter((p) => p.startsWith('color.')).map((p) => p.split('.')[1]))];
for (const g of groups) {
  w();
  w(`### ${g}`);
  w();
  w('| Token | Light | Dark | Contrast ☀ / ☾ | Use |');
  w('|---|---|---|---|---|');
  for (const [p, t] of L) {
    if (!p.startsWith(`color.${g}.`)) continue;
    const d = D.get(p);
    const on = measuredOn(p);
    let cr = '';
    if (on && L.get(on) && (t.value.alpha ?? 1) >= 1) cr = `${contrast(hex(t), hex(L.get(on))).toFixed(2)} / ${contrast(hex(d), hex(D.get(on))).toFixed(2)} on \`${kebab(on.slice(6))}\``;
    w(`| \`${kebab(p)}\` | \`${hex(t)}\`${prim(t)} | \`${hex(d)}\`${prim(d)} | ${cr} | ${esc(t.description)} |`);
  }
}
for (const p of [...all.base.keys()].filter((k) => k.startsWith('color.external.'))) {
  if (p === [...all.base.keys()].find((k) => k.startsWith('color.external.'))) { w(); w('### external (never themed)'); w(); w('| Token | Value | Use |'); w('|---|---|---|'); }
  const t = all.base.get(p);
  w(`| \`${kebab(p)}\` | \`${hex(t)}\` | ${esc(t.description)} |`);
}

w();
w('## Primitive palette');
w();
w('Raw ramps. Maintainers only: never bind these inside components.');
const ramps = {};
for (const [p, t] of all.base) {
  const m = p.match(/^primitive\.color\.(\w+)\.(.+)$/);
  if (!m || m[2].startsWith('alpha')) continue;
  (ramps[m[1]] ??= []).push([m[2], hex(t)]);
}
for (const [r, steps] of Object.entries(ramps)) {
  w();
  w(`**${r}** — ` + steps.map(([s, h]) => `${s} \`${h}\``).join(' · '));
}

const table = (title, prefix, src = all.base, unit = 'px') => {
  const rows = [...src].filter(([p]) => p.startsWith(prefix));
  if (!rows.length) return;
  w();
  w(`## ${title}`);
  w();
  w('| Token | Value | Use |');
  w('|---|---|---|');
  for (const [p, t] of rows) {
    const v = typeof t.value === 'object' ? JSON.stringify(t.value) : `${t.value}${typeof t.value === 'number' && unit ? unit : ''}`;
    w(`| \`${kebab(p)}\` | ${esc(v)} | ${esc(t.description)} |`);
  }
};
table('Spacing', 'spacing.');
table('Radius', 'radius.');
table('Border width', 'border.');
table('Size', 'size.');
table('Motion', 'motion.', all.base, '');
table('Layers (z-index)', 'layer.', all.base, '');

w();
w('## Elevation');
w();
w('| Token | Light | Dark |');
w('|---|---|---|');
for (const [p, t] of L) if (p.startsWith('elevation.') || p.startsWith('shadow.')) w(`| \`${kebab(p)}\` | \`${esc(t.value)}\` | \`${esc(D.get(p).value)}\` |`);

const plat = (title, re) => {
  const keys = [...new Set(Object.values(all.platform).flatMap((m) => [...m.keys()]))].filter((k) => re.test(k));
  if (!keys.length) return;
  w();
  w(`## ${title}`);
  w();
  w('| Token | Web | Tablet | Mobile |');
  w('|---|---|---|---|');
  for (const k of keys) w(`| \`${kebab(k)}\` | ${['web', 'tablet', 'mobile'].map((m) => esc(all.platform[m].get(k)?.value ?? '—')).join(' | ')} |`);
};
plat('Typography — sizes', /^font\.size\./);
plat('Typography — weights', /^font\.weight\./);
plat('Typography — line heights', /^font\.line-height\./);
plat('Grid, layout and breakpoints', /^(grid|layout|breakpoint|target)\./);

fs.writeFileSync(path.join(TOKENS, 'Biowave Foundations.md'), out.join('\n') + '\n');
console.log('✓ foundations reference: 2-foundations/tokens/Biowave Foundations.md');
